# -*- coding: utf-8 -*-
"""Поиск времени на странице расписания.

Раньше эта логика жила отдельно в `probe_browser.py` и `reanalyze_browser.py`
и успела разъехаться. Здесь она одна на всех.

Пять случаев, на которых мы уже обожглись:

1. **Координаты в картинках.** Первая версия считала временем любое `19.30`,
   и на 2plus2.ua набралось 850 «меток», которые оказались координатами SVG
   (`26.49`, `16.06`). Лечится полной очисткой: скрипты, стили и все теги
   вырезаются целиком, вместе с атрибутами.

2. **Время через точку.** `diemaxtra.nova.bg` пишет `06.30`, `trt.net.tr` —
   `05.13`. После запрета точки эти сайты выглядели пустыми. Точку вернули,
   но с проверкой: даты `01.09`, `02.09` тоже выглядят как время, поэтому
   значения с точкой засчитываются, только если среди них есть хотя бы три
   с «минутами» больше 12 — месяцев больше 12 не бывает.

3. **Время, разорванное вёрсткой.** На `trtavaz.com.tr` часы и минуты лежат
   в разных кусочках разметки, и после вырезания тегов между ними появляется
   пробел: `05 :58`. Находилось 0 меток вместо 47. Лечится склейкой пробелов
   вокруг разделителя.

4. **Французское время `21h10`.** `programme-tv.net` пишет час и минуты через
   букву «h». Находилось 0 меток, и сайт ошибочно записали в платные. Рядом
   тот же сайт пишет длительность передачи — `1h30min`; её нужно отсеивать,
   иначе к 44 настоящим меткам добавляется 33 ложных.

5. **Оборванная страница.** Копию страницы раньше обрезали на 600 000 знаков,
   и обрыв нередко приходился на середину `<style>` или картинки. Закрывающего
   тега нет — и весь хвост, то есть оформление и координаты, считался обычным
   текстом. Так `protv.ro` получил «4607 меток времени», хотя расписания на
   странице не было вовсе. Поэтому незакрытый блок вырезается до конца файла,
   а разметка, приехавшая в виде текста (`&lt;path d=...&gt;`), — тоже.
"""

from __future__ import annotations

import re

# ── очистка страницы ─────────────────────────────────────────────────────────

# `(?:</script>|\Z)` — блок без закрывающего тега (страница оборвалась)
# вырезается до конца файла, иначе его содержимое сойдёт за текст.
_DROP_BLOCKS = re.compile(
    r"<script.*?(?:</script>|\Z)"
    r"|<style.*?(?:</style>|\Z)"
    r"|<noscript.*?(?:</noscript>|\Z)",
    re.S | re.I)
# разметка, попавшая на страницу как текст: `&lt;path d=&quot;M7.07 9.81…`
_DROP_ESCAPED = re.compile(r"&lt;.*?(?:&gt;|\Z)", re.S)
_DROP_ATTRS = re.compile(r'\shref="[^"]*"|\ssrc="[^"]*"')
_DROP_TAGS = re.compile(r"<[^>]+>")
_SPACES = re.compile(r"\s+")

# пробелы вокруг разделителя времени: «05 : 58», «07: 00», «21 h 10»
_GLUE = re.compile(r"(?<=\d)\s*([:.h])\s*(?=\d)")


def normalize(text: str) -> str:
    """Готовый видимый текст (например `inner_text` из браузера): склеиваем
    время, разорванное вёрсткой."""
    return _GLUE.sub(r"\1", _SPACES.sub(" ", text))


def clean(html: str) -> str:
    """HTML без скриптов, стилей и тегов — остаётся только видимое содержание.
    Разорванное вёрсткой время склеивается обратно."""
    s = _DROP_BLOCKS.sub(" ", html)
    s = _DROP_ESCAPED.sub(" ", s)        # разметка, приехавшая текстом
    s = _DROP_ATTRS.sub(" ", s)          # рекламные адреса с цифрами
    s = _DROP_TAGS.sub(" ", s)
    return normalize(s)


# ── поиск меток времени ──────────────────────────────────────────────────────

COLON = re.compile(r"(?<!\d)([01]?\d|2[0-3]):([0-5]\d)(?!\d)")
DOT = re.compile(r"(?<!\d)([01]?\d|2[0-3])\.([0-5]\d)(?!\d)")
# французское `21h10`; `(?!\s*min)` отсекает длительность вида `1h30min`
H = re.compile(r"(?<![\d\w])([01]?\d|2[0-3])[hH]([0-5]\d)(?!\d)(?!\s*min)")

# сколько значений с «минутами» больше 12 должно найтись, чтобы поверить,
# что точка здесь разделяет часы и минуты, а не день и месяц
MIN_NON_MONTH = 3


def dot_is_time(text: str) -> bool:
    """Точка на этой странице разделяет часы и минуты, а не день и месяц?"""
    tails = [int(m.group(2)) for m in DOT.finditer(text)]
    return sum(1 for t in tails if t > 12) >= MIN_NON_MONTH


def find(text: str) -> list[str]:
    """Все метки времени на очищенной странице. Точка учитывается только там,
    где она действительно означает время."""
    marks = [f"{m.group(1)}:{m.group(2)}" for m in COLON.finditer(text)]
    marks += [f"{m.group(1)}:{m.group(2)}" for m in H.finditer(text)]
    if dot_is_time(text):
        marks += [f"{m.group(1)}:{m.group(2)}" for m in DOT.finditer(text)]
    return marks


def count(text: str) -> int:
    return len(find(text))


def describe(text: str) -> str:
    """Короткая пометка для колонки notes: чем именно разделено время."""
    colon, dot, h = len(COLON.findall(text)), len(DOT.findall(text)), len(H.findall(text))
    parts = []
    if dot and dot_is_time(text):
        parts.append("через точку")
    if h:
        parts.append("французское 21h10")
    if not parts:
        return ""
    if colon:
        parts.insert(0, "через двоеточие")
    return "время " + " и ".join(parts)
