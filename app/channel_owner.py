# -*- coding: utf-8 -*-
"""Чей это канал: его собственный сайт или агрегатор — всё решение здесь.

Правило владельца 07.10.2026 (вопрос №2112 «Fateh — Ahli»): «зачем ты берёшь
расписание Sport Klub-ов с mojtv.hr, если есть более правильное —
sportklub.hr»; и далее: «можно брать на ту глубину, которую даёт официальный
сайт, 1+4 дня. А остальное, то, чего нет у нас официальных сайтов, продолжай
брать как брал».

Отсюда и правила. Официальным источник делает отметка в его карточке
(`selector_config.official = true`, ставит `scripts/set_official.py`) — это
настройка данных, а не список каналов в коде: завели новый официальный сайт,
пометили, и его каналы сами перешли на это правило.

Глубину официального сайта не задаём числом: её видно по самим сборам — это
самый дальний день, на который сайт дал хоть одну передачу. Сайт стал давать
на день больше — правило подтянется само; сайт сломался и не дал ничего —
агрегатор снова берётся целиком, витрина не пустеет.

Смотрим и базу, и заливаемый файл. Только файла мало: `mojtv.hr` закрыт для
GitHub, его качает сам сервер отдельным сбором (`scripts/server_crawl.py`),
и в том файле официального сайта нет вовсе — глубину тогда берём из отметок
официального источника в базе, которые он подтвердил за последние
`СВЕЖЕСТЬ_ЧАСОВ`. Старше — не считаем: это уже не «сайт показывает день», а
память о прошлой неделе.

Правила по порядку (их номера — в `Хозяева.почему`):

 1. Строка самого официального сайта — берём всегда.
 2. У канала нет официального сайта (ни один официальный источник его в этом
    сборе не дал) — строку агрегатора берём: 93 канала из 316 живут только
    агрегаторами, отключить их значит потерять (замер 06.10, задача «найти
    официальное расписание для каждого канала» — в `ОТЛОЖЕНО.md`).
 3. День игры не дальше, чем глубина официального сайта в этом сборе, —
    строку агрегатора НЕ берём: официальный сайт этот день показал, и если
    матча на канале у него нет, значит матча там нет.
 4. День дальше глубины официального — берём: дальние дни официальный ещё не
    опубликовал, и агрегатор остаётся запасом (слово владельца: «mojtv —
    запасом и для каналов, которых больше нигде нет»).

Строку, которую правило 3 не пустило, заливка не просто пропускает, а СНИМАЕТ
прежнюю отметку этого агрегатора по этому каналу и этой игре; а в конце
заливки `дочистить` снимает и хвосты — отметки агрегаторов за дни в глубине
хозяина, которых в файле уже не было (08.10: 22 такие висели после двух
сборов). Игру без единого живого канала ни то, ни другое не оставляет. Иначе она
осталась бы на витрине навсегда: подтверждать её мы перестали, а гашение
`app/miss.py` её не возьмёт — у сайта разом «пропала» почти вся его линейка,
и правило 6 (доля игр) справедливо считает это поломкой разбора, а не
отменой матчей. Потеря не безвозвратная: снимут отметку `official` — и
следующий сбор агрегатора вернёт свои строки.
"""

from __future__ import annotations

import json
import sqlite3
from datetime import datetime, timedelta

#: отметка официального сайта в карточке источника (`selector_config`)
ФЛАГ = "official"

#: насколько свежей должна быть отметка официального сайта, чтобы считать её
#: за «сайт этот день показывает». Сутки с запасом: `sportklub.hr` обходится
#: трижды в день, а сервер качает `mojtv.hr` раз в сутки
СВЕЖЕСТЬ_ЧАСОВ = 30


def официальные(conn: sqlite3.Connection) -> dict[int, str]:
    """`id` → домен тех источников, что помечены официальными."""
    out: dict[int, str] = {}
    for row in conn.execute(
            "SELECT id, domain, selector_config FROM sources WHERE enabled = 1"):
        try:
            config = json.loads(row["selector_config"] or "{}") or {}
        except ValueError:
            continue
        if config.get(ФЛАГ):
            out[row["id"]] = row["domain"]
    return out


class Хозяева:
    """Кто хозяин канала в этом сборе и чьи строки по нему берём.

    Пользоваться так: сперва `учесть` каждую строку официального источника
    (первый проход по файлу), затем `пропустить` для каждой строки обычного
    (второй проход, он же заливка).
    """

    def __init__(self, conn: sqlite3.Connection,
                 now: datetime | None = None):
        self.официальные = официальные(conn)
        #: канал → официальные источники, которые его дают
        self.хозяин: dict[int, set[int]] = {}
        #: официальный источник → самый дальний его день (ГГГГ-ММ-ДД)
        self.глубина: dict[int, str] = {}
        #: сколько строк не пустило правило 3, по домену агрегатора
        self.пропущено: dict[str, int] = {}
        if self.официальные:
            self._из_базы(conn, now or datetime.now())

    def _из_базы(self, conn: sqlite3.Connection, now: datetime) -> None:
        """Чьи каналы и до какого дня их сайт дотягивается — по базе.

        Нужно для сборов, где официального сайта нет вовсе: `mojtv.hr`
        сервер качает отдельно, и без базы его строки по Sport Klub
        выглядели бы «каналом без хозяина»."""
        места = ", ".join("?" * len(self.официальные))
        ключи = list(self.официальные)
        for row in conn.execute(
                "SELECT channel_id, source_id FROM channel_aliases "
                f"WHERE source_id IN ({места})", ключи):
            self.хозяин.setdefault(row["channel_id"], set()).add(row["source_id"])
        порог = (now - timedelta(hours=СВЕЖЕСТЬ_ЧАСОВ)).strftime("%Y-%m-%d %H:%M")
        for row in conn.execute(
                "SELECT ec.source_id AS source_id, MAX(e.start_kyiv) AS день "
                "FROM event_channels ec JOIN events e ON e.id = ec.event_id "
                f"WHERE ec.source_id IN ({места}) AND ec.last_seen >= ? "
                "GROUP BY ec.source_id", (*ключи, порог)):
            if row["день"]:
                self.глубина[row["source_id"]] = row["день"][:10]

    def свой(self, source_id: int) -> bool:
        """Источник помечен официальным (правило 1)."""
        return source_id in self.официальные

    def учесть(self, source_id: int, channel_id: int, день: str) -> None:
        """Строка официального источника: канал его, день — в его глубину."""
        if not self.свой(source_id):
            return
        self.хозяин.setdefault(channel_id, set()).add(source_id)
        if день > self.глубина.get(source_id, ""):
            self.глубина[source_id] = день

    def почему(self, source_id: int, channel_id: int, день: str) -> int:
        """Номер сработавшего правила (3 — строку не берём, остальные — берём)."""
        if self.свой(source_id):
            return 1
        хозяева = self.хозяин.get(channel_id)
        if not хозяева:
            return 2
        if any(день <= self.глубина.get(х, "") for х in хозяева):
            return 3
        return 4

    def пропустить(self, source_id: int, channel_id: int, день: str,
                   domain: str = "") -> bool:
        """Не брать эту строку агрегатора (правило 3)."""
        if self.почему(source_id, channel_id, день) != 3:
            return False
        ключ = domain or str(source_id)
        self.пропущено[ключ] = self.пропущено.get(ключ, 0) + 1
        return True

    def дочистить(self, conn: sqlite3.Connection) -> int:
        """Хвосты: живые отметки агрегаторов по каналам с хозяином за дни, что
        хозяин показывает, — которых в этом файле уже не было.

        Правило 3 в заливке снимает только те отметки, чьи строки сайт
        прислал снова. Строку, которую агрегатор перестал показывать, его
        гашение (`app/miss.py`, правило 6) не берёт — мы сами выкинули ему
        почти всю линейку, и доля игр у него «просела». Так 08.10 после двух
        сборов `mojtv.hr` по Sport Klub осталось 22 отметки на дни, которые
        `sportklub.hr` давно показывает. Снимаем их здесь; игру без единого
        живого канала не оставляем. Вернёт число снятых."""
        if not self.официальные:
            return 0
        места = ", ".join("?" * len(self.официальные))
        снято = 0
        for channel_id, хозяева in self.хозяин.items():
            глубина = max((self.глубина.get(х, "") for х in хозяева), default="")
            if not глубина:
                continue
            хвосты = conn.execute(
                "SELECT ec.id, ec.event_id FROM event_channels ec "
                "JOIN events e ON e.id = ec.event_id "
                "WHERE ec.channel_id = ? AND ec.miss_count = 0 "
                "AND substr(e.start_kyiv, 1, 10) <= ? "
                f"AND ec.source_id NOT IN ({места})",
                (channel_id, глубина, *self.официальные)).fetchall()
            for хвост in хвосты:
                другая = conn.execute(
                    "SELECT 1 FROM event_channels WHERE event_id = ? "
                    "AND miss_count = 0 AND id != ? LIMIT 1",
                    (хвост["event_id"], хвост["id"])).fetchone()
                if not другая:
                    continue                 # единственный канал игры — бережём
                conn.execute("DELETE FROM event_channels WHERE id = ?",
                             (хвост["id"],))
                снято += 1
        return снято

    def отчёт(self, снято: int = 0) -> str:
        """Строка для журнала заливки; пусто — если ничего не пропускали.
        `снято` — сколько прежних отметок тех же агрегаторов убрала заливка."""
        if not self.пропущено:
            return ""
        части = ", ".join(f"{домен}: {сколько}" for домен, сколько
                          in sorted(self.пропущено.items()))
        хвост = f"; снято прежних отметок: {снято}" if снято else ""
        return ("строк агрегаторов не взято — у канала есть свой сайт "
                f"({части}){хвост}")
