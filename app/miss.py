# -*- coding: utf-8 -*-
"""Гасить ли канал игры — всё решение в одном месте.

Канал у игры гаснет (на витрине перечёркнут «снят», в API не отдаётся),
когда сбор ДОКАЗАЛ, что сайт этого канала матч на нём больше не показывает
(правило владельца 03.10: хватает одного такого сбора, `store.MISS_LIMIT`).
Доказательство — только когда выполнено ВСЁ сразу. Правила по порядку, в
том же порядке идут ветки `Гашение.почему_нельзя`:

 1. Файл сбора новый. Повторная заливка того же файла (`--reimport`) не
    гасит ничего (05.09: три заливки одного прогона погасили 14 каналов).
 2. Игра есть в этом сборе — её подтвердил хоть один канал (или это
    заголовок турнира без пары, который сайты перестали писать,
    `app/broadcast.py`). Игра, которой в файле нет ВОВСЕ, — сирота: сайт
    перенёс матч на другой день (#5104 Motherwell — Celtic, 09.10: teleman
    с субботы переставил на воскресенье, а субботняя запись висела с живым
    каналом до начала + грейс). Слово владельца 09.10: «если игра не
    встретилась — проверить её на сайте и снять, хотя бы канал
    перечеркнуть». Поэтому сироты идут по правилам 3–6 как все
    (`store.save_games`, «сироты»): доказательство то же — сайт ответил,
    страница того же вида за день игры цела и игр на день дал достаточно.
 3. Игра ещё не началась к моменту сбора. Сайты, отдающие только остаток
    дня (nova.bg, tvarenasport — ГРАБЛИ), начавшийся матч уже не пишут, и
    это не отмена.
 4. Сайт канала в этом сборе ответил (не «не открылась», не заглушка).
 5. Сбор скачал страницу ТОГО ЖЕ ВИДА, с которой пришла отметка (сайт и
    путь адреса без чисел, `вид_адреса`), за ТОТ ЖЕ ДЕНЬ, и она дала
    расписание. Другой вид страницы того же сайта — не доказательство:
    скан даты 06.10 брал у teleman.pl страницы каналов, а отметки пришли
    из общего списка `/sport`, где у тенниса есть пары игроков, а на
    странице канала их нет. Среди страниц этого вида канал узнан по
    написанию — нужна целая страница ИМЕННО этого канала (упала страница
    канала A — гаснуть A не за что, даже если страница B открылась); не
    узнан — целыми должны быть все страницы этого вида за день. Сетка без
    дня приносит сразу всё окно.
    День страницы — не киевская дата игры (`дни_страницы`). Ночную игру
    показывает лист прошлых суток: ТВ-сутки идут до 05:00–06:00, сайты
    западнее Киева ещё во вчерашнем дне — Argentina — Benin 07.10 01:50
    пришла со страниц 06.10 ziggosport, ntvplus, oneplay, tvsporten, и скан
    даты 07.10 гасил её семь живых отметок (проверка 06.10). Поэтому:
    а) адрес отметки несёт дату (`дата_в_адресе`), и адреса того же вида в
       этом сборе несут дату своего дня — день страницы и есть эта дата;
    б) иначе — день игры по Киеву, а у игры до `НОЧЬ_ДО` по Киеву ещё и
       день накануне: целыми должны быть страницы обоих дней;
    в) листаемый список (teleman `/sport?live=1&page=N`, в отчёте
       `window`): страницы идут по времени через все дни окна, а «день» у
       них — якорь сбора. Такой вид покрывает любой день, но доказательство
       требует, чтобы список ДОШЁЛ дальше дня игры — сайт в этом сборе дал
       хоть одну игру на более поздний день. Иначе день мог оборваться на
       последней странице (#5104, 09.10: Motherwell — Celtic висел на
       субботе, а список teleman уже писал воскресенье).
 6. Сайт в этом сборе дал на этот день игры, и не меньше доли
    `ДОЛЯ_ИГР` от отметок, что у него уже живут на этот день. «Расписание
    есть», а игр 0 — значит разбор не понял страницу (06.10: скан даты
    сдвинул день у teleman.pl и погасил 9 из 10 его отметок, #4224),
    а не что сайт снял матчи.

Не выполнено хоть одно — отметка остаётся как была. Выполнено всё —
счётчик пропусков +1. Правило владельца 03.10 работает как раньше: сайт
перенёс матч с канала на канал (#2579, maxsport.live) — страница цела, игры
у сайта есть, старый канал гаснет.
"""

from __future__ import annotations

import math
import re
import sqlite3
from dataclasses import dataclass, field
from datetime import date, timedelta
from urllib.parse import unquote, urlsplit

#: итоги страницы из отчёта обхода (`report.json`, поле «итог»)
РАСПИСАНИЕ_ЕСТЬ = "расписание есть"
НЕ_ОТВЕТИЛ = ("не открылась", "заглушка защиты")

#: правило 6: сколько игр должен дать сайт на день от числа его живых
#: отметок на этот день, чтобы сбор был вправе гасить. Половина — сайт может
#: честно снять часть матчей, но «вдвое меньше обычного» — уже сломанный
#: разбор, а не решение сайта
ДОЛЯ_ИГР = 0.5

#: правило 5б: игра раньше этого часа по Киеву — ночная, её может держать
#: страница прошлых суток. ТВ-сутки сайтов кончаются в 05:00–06:00 своего
#: времени, а 06:00 Лиссабона или Лондона — это 08:00 Киева
НОЧЬ_ДО = 8

#: правило 5а: дата в адресе страницы. Год впереди — `2026-10-06`,
#: `2026/10/06`; год в конце — `06.10.2026`, `06-10-2026`, `06/10/2026`
#: (у sport5 `%2F` — тот же `/`, адрес раскодируется до поиска)
_ДАТА_ГОД_ВПЕРЕДИ = re.compile(r"(?<!\d)(\d{4})[-/](\d{1,2})[-/](\d{1,2})(?!\d)")
_ДАТА_ГОД_В_КОНЦЕ = re.compile(r"(?<!\d)(\d{1,2})[-./](\d{1,2})[-./](\d{4})(?!\d)")


def _bare(domain: str) -> str:
    return (domain or "").strip().lower().removeprefix("www.")


def вид_адреса(url: str) -> str:
    """Вид страницы: сайт и путь без чисел и без запроса (правило 5).
    `https://www.teleman.pl/program-tv/stacje/Polsat-Sport-2?date=2026-10-06`
    → `teleman.pl/program-tv/stacje/Polsat-Sport-#`. Числа в пути — дата,
    номер дня или страницы: от сбора к сбору они меняются, а вид — нет."""
    части = urlsplit(url or "")
    return (_bare(части.netloc) + re.sub(r"\d+", "#", части.path)).rstrip("/")


def дата_в_адресе(url: str) -> str:
    """Первая дата, написанная в адресе, как `ГГГГ-ММ-ДД`; нет — пусто
    (правило 5а). `…epg-2026-10-06.json`, `…?date=06.10.2026`,
    `…?date=06%2F10%2F2026` → `2026-10-06`. Номер дня (`?d=1`), день
    недели и метка UNIX датой не считаются: у них один адрес в разные дни
    значит разные страницы."""
    текст = unquote(url or "")
    найдено = []
    for m in _ДАТА_ГОД_ВПЕРЕДИ.finditer(текст):
        найдено.append((m.start(), m.group(1), m.group(2), m.group(3)))
    for m in _ДАТА_ГОД_В_КОНЦЕ.finditer(текст):
        найдено.append((m.start(), m.group(3), m.group(2), m.group(1)))
    for _, год, месяц, день in sorted(найдено):
        try:
            return date(int(год), int(месяц), int(день)).isoformat()
        except ValueError:
            continue
    return ""


@dataclass
class Покрытие:
    """Что сбор реально скачал — по строкам отчёта обхода."""
    #: домены, которые ответили хоть одной страницей (правило 4)
    ответили: set[str] = field(default_factory=set)
    #: (вид адреса, день) → канал строки → дала ли страница расписание
    #: (правило 5). Канал "" — сетка (все её страницы должны быть целы);
    #: день "" — сетка без дня, приносит сразу всё окно
    страницы: dict[tuple[str, str], dict[str, bool]] = field(default_factory=dict)
    #: вид адреса → у ВСЕХ его строк с днём в этом сборе адрес несёт дату
    #: своего дня (правило 5а). Вида нет — сбор его не качал, судить не о чем
    датированы: dict[str, bool] = field(default_factory=dict)
    #: виды адресов листаемых списков — страница несёт всё окно (правило 5в)
    окно: set[str] = field(default_factory=set)

    def дни_страницы(self, адрес: str, start: str) -> list[str]:
        """Правило 5: за какие дни страница вида `адрес` могла держать
        отметку игры, начатой в `start` (Киев, `ГГГГ-ММ-ДД ЧЧ:ММ`).
        Целыми должны быть страницы ВСЕХ этих дней."""
        if self.датированы.get(вид_адреса(адрес)):
            день = дата_в_адресе(адрес)
            if день:
                return [день]                               # 5а
        день = start[:10]
        if int(start[11:13]) < НОЧЬ_ДО:                     # 5б
            накануне = date.fromisoformat(день) - timedelta(days=1)
            return [накануне.isoformat(), день]
        return [день]

    def страница_цела(self, адрес: str, день: str, имена: set[str]) -> bool:
        """Правило 5: скачана ли и дала ли расписание на этот день страница
        того же вида, что адрес отметки, — для канала с этими написаниями."""
        вид = вид_адреса(адрес)
        for ключ in ((вид, ""), (вид, день)):
            каналы = self.страницы.get(ключ)
            if not каналы:
                continue
            свои = [ok for канал, ok in каналы.items() if канал in имена]
            return any(свои) if свои else all(каналы.values())
        return False


def покрытие_из_отчёта(строки: list[dict]) -> Покрытие:
    """Строки `report.json` → `Покрытие`. Страница с итогом «пусто» гасить
    не вправе: пустой ответ — не доказательство, что матча больше нет."""
    итог = Покрытие()
    for строка in строки:
        вердикт = строка.get("итог")
        if вердикт not in НЕ_ОТВЕТИЛ:
            итог.ответили.add(_bare(строка["domain"]))
        ok = вердикт == РАСПИСАНИЕ_ЕСТЬ
        канал = строка.get("channel") or ""
        адрес, день = строка.get("url") or "", строка.get("day") or ""
        вид = вид_адреса(адрес)
        if строка.get("window"):
            # листаемый список: день в строке — якорь сбора, страницы несут
            # всё окно (правило 5в) — как сетка без дня
            итог.окно.add(вид)
            день = ""
        if день:
            # правило 5а: вид датирован, пока каждая его строка несёт в
            # адресе дату своего дня
            итог.датированы[вид] = итог.датированы.get(вид, True) \
                and дата_в_адресе(адрес) == день
        каналы = итог.страницы.setdefault((вид, день), {})
        if канал:
            # один канал за день бывает в двух строках (добор по ссылкам
            # ORF): хватает одной целой
            каналы[канал] = каналы.get(канал, False) or ok
        else:
            # сетка постранично (teleman `/sport?page=N`): выпала одна
            # страница — пропали и её матчи, значит целы должны быть все
            каналы[""] = каналы.get("", True) and ok
    return итог


class Гашение:
    """Решает по правилам из шапки модуля, можно ли погасить отметку.

    Создаётся ДО записи игр файла в базу: правилу 6 нужны отметки, которые
    жили на каждый день до этой заливки. Пока игры файла пишутся, `учесть`
    копит, что сайт дал в этом сборе."""

    def __init__(self, conn: sqlite3.Connection, покрытие: Покрытие | None,
                 свежий: bool, собрано: str, предел: int) -> None:
        self.conn = conn
        self.покрытие = покрытие
        self.свежий = свежий
        #: момент сбора по Киеву `ГГГГ-ММ-ДД ЧЧ:ММ` (правило 3); пусто —
        #: момент неизвестен, правило 3 молчит
        self.собрано = собрано
        self.домен_по_id = {r[0]: r[1] for r in conn.execute(
            "SELECT id, domain FROM sources")}
        # правило 6: живые отметки ещё не начавшихся игр по (сайт, день)
        self.жили: dict[tuple[int, str], int] = {}
        for sid, день, n in conn.execute(
                "SELECT ec.source_id, substr(e.start_kyiv, 1, 10), COUNT(*) "
                "FROM event_channels ec JOIN events e ON e.id = ec.event_id "
                "WHERE ec.miss_count < ? AND e.start_kyiv > ? "
                "GROUP BY 1, 2", (предел, собрано)):
            self.жили[(sid, день)] = n
        self.дал: dict[tuple[int, str], set[tuple[int, int]]] = {}
        self._имена: dict[tuple[int, int], set[str]] = {}

    def учесть(self, source_id: int, день: str, event_id: int,
               channel_id: int) -> None:
        """Сайт в этом сборе показал игру на этом канале (для правила 6)."""
        self.дал.setdefault((source_id, день), set()).add((event_id, channel_id))

    def _имена_канала(self, channel_id: int, source_id: int) -> set[str]:
        """Как этот сайт пишет канал: по этим написаниям ищем его страницу
        среди строк отчёта (правило 5)."""
        ключ = (channel_id, source_id)
        if ключ not in self._имена:
            self._имена[ключ] = {r[0] for r in self.conn.execute(
                "SELECT alias FROM channel_aliases WHERE channel_id = ? "
                "AND (source_id = ? OR source_id IS NULL)",
                (channel_id, source_id))}
        return self._имена[ключ]

    def почему_нельзя(self, *, source_id: int, channel_id: int, адрес: str,
                      start: str, в_сборе: bool) -> str:
        """Пусто — гасить можно; иначе — номер и суть нарушенного правила.
        `адрес` — страница, с которой пришла отметка (`source_url`),
        `start` — начало игры по Киеву `ГГГГ-ММ-ДД ЧЧ:ММ`."""
        день = start[:10]          # правило 6 считает игры по киевской дате
        if not self.свежий:
            return "1: файл уже вливали"
        if not в_сборе:
            return "2: игры нет в этом сборе"
        if self.собрано and start <= self.собрано:
            return "3: игра началась до сбора"
        домен = _bare(self.домен_по_id.get(source_id, ""))
        if self.покрытие is None or домен not in self.покрытие.ответили:
            return "4: сайт в этом сборе не ответил"
        имена = self._имена_канала(channel_id, source_id)
        if not all(self.покрытие.страница_цела(адрес, d, имена)
                   for d in self.покрытие.дни_страницы(адрес, start)):
            return "5: страница того же вида на этот день не скачана"
        if вид_адреса(адрес) in self.покрытие.окно and not any(
                sid == source_id and d > день for sid, d in self.дал):
            return "5в: листаемый список не дошёл до дня после игры"
        дал = len(self.дал.get((source_id, день), ()))
        жили = self.жили.get((source_id, день), 0)
        if дал == 0 or дал < math.ceil(жили * ДОЛЯ_ИГР):
            return f"6: сайт дал на день {дал} игр при {жили} живых отметках"
        return ""
