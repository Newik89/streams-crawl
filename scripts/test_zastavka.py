# -*- coding: utf-8 -*-
r"""«Нечётная» минута угаданного эфира (`parse_live.odd_minute_record`):

1. начало на :00/:05/…/:55 — не запись;
2. заставка: показ за 0–10 мин до начала ТОГО ЖЕ матча по эталону — эфир
   (самопроверка №13 на сборе #249: у movistarplus 12 живых ЛЧ/ЛЕ/Liga
   Endesa в 19:38 и 21:53 снимались как записи — книга случаев 050);
3. иначе — запись: повтор стартует, где кончился прошлый блок
   (`Man Utd - Ipswich` в 00:17 у movistarplus, владелец 02.09).

В сеть не ходит:
    python scripts/test_zastavka.py
"""

from __future__ import annotations

import os
import sys
import tempfile
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
sys.stdout.reconfigure(encoding="utf-8")
os.environ.setdefault("STREAMS_DB", str(Path(tempfile.mkdtemp()) / "none.db"))

import parse_live  # noqa: E402

зелёных = красных = 0


def проверка(имя: str, вышло, ждём) -> None:
    global зелёных, красных
    if вышло == ждём:
        зелёных += 1
        print(f"  ✔ {имя}")
    else:
        красных += 1
        print(f"  ✗ {имя}: вышло {вышло!r}, ждали {ждём!r}")


def t(text: str) -> datetime:
    return datetime.fromisoformat(text)


запись = parse_live.odd_minute_record
print("1. ровная минута — не запись")
проверка("21:00 без эталона", запись(t("2026-10-13T21:00"), None), False)
проверка("19:45 — ровная", запись(t("2026-10-13T19:45"), t("2026-10-13T19:45")), False)
print("2. заставка перед матчем — эфир (книга 050)")
проверка("19:38 при начале 19:45 (Lens — Sporting, M+ Liga de Campeones 2)",
         запись(t("2026-10-13T19:38"), t("2026-10-13T19:45")), False)
проверка("21:53 при начале 22:00", запись(t("2026-10-13T21:53"), t("2026-10-13T22:00")), False)
проверка("17:51 при начале 18:00 (Liga Endesa)",
         запись(t("2026-10-18T17:51"), t("2026-10-18T18:00")), False)
проверка("ровно за 10 мин — ещё заставка",
         запись(t("2026-10-13T19:49"), t("2026-10-13T19:59")), False)
проверка("M4 Sport за 3 мин (mediaklikk)", запись(t("2026-10-16T20:57"), t("2026-10-16T21:00")), False)
print("3. прочие нечётные минуты — запись (правило владельца 02.09)")
проверка("00:17 — повтор вчерашнего матча (Man Utd — Ipswich)",
         запись(t("2026-09-02T00:17"), t("2026-09-01T21:00")), True)
проверка("03:47 без эталона рядом", запись(t("2026-09-02T03:47"), None), True)
проверка("студия «Previa Euroliga» за 14 мин — не эфир (сбор #249)",
         запись(t("2026-10-13T21:16"), t("2026-10-13T21:30")), True)
проверка("за 11 мин — уже не заставка", запись(t("2026-10-13T19:34"), t("2026-10-13T19:45")), True)
проверка("через 2 мин после начала — запись", запись(t("2026-10-13T19:47"), t("2026-10-13T19:45")), True)

print(f"\nпроверок: {зелёных + красных}, зелёных: {зелёных}, красных: {красных}")
sys.exit(1 if красных else 0)
