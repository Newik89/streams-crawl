# -*- coding: utf-8 -*-
r"""Книга 154 (16.11.2026): греческие сокращения сторон света перед названием.

Находка: «Ν. Κορέα» (так греческие сетки пишут Южную Корею) читалась буквами
«N KOREA», и инициал «N» закрывался словом «North» — Южная Корея сходилась с
«North Korea» на 100, а со своей «South Korea» — на 0. Правила Г1–Г5 —
`app/names.py`, над `_GREEK_COMPASS`:
  Г1. буква с точкой в начале имени перед греческим словом — сокращение:
      «Ν.» — «Νότια/Νέα», «Β.» — «Βόρεια», «Α.» — «Ανατολική», «Δ.» — «Δυτική»;
  Г2. раскрытие проверяется точным знанием: справочник стран и подтверждённые имена;
  Г3. узнано — остаются только узнанные чтения, голого инициала нет;
  Г4. не узнано — имя читается буквами, как раньше;
  Г5. буква после фамилии — инициал человека, правило его не трогает.
В сеть не ходит. Запуск: python scripts/test_grecheskie_sokrashcheniya.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.stdout.reconfigure(encoding="utf-8")

from app import canon, names  # noqa: E402

зелёных = красных = 0


def проверка(имя: str, вышло, ждём=True) -> None:
    global зелёных, красных
    if вышло == ждём:
        зелёных += 1
        print(f"  ✔ {имя}")
    else:
        красных += 1
        print(f"  ✘ {имя}: вышло {вышло!r}, ждём {ждём!r}")


print("Г1–Г3. Сокращение перед названием страны раскрывается и сверяется со справочником")
проверка("«Ν. Κορέα» — Южная Корея: страна, единственное чтение, со своей — 100, с Северной — ниже порога",
         (names.country_of("Ν. Κορέα"), names.readings("Ν. Κορέα"), names.similarity("Ν. Κορέα", "South Korea"),
          names.similarity("Ν. Κορέα", "North Korea") < canon.SURE, names.similarity("Ν. Κορέα", "DPR Korea") < canon.SURE),
         ("SOUTH KOREA", ("SOUTH KOREA",), 100, True, True))
проверка("«Ν.» — и «Νότια», и «Νέα», в любом роде: Новая Зеландия, ЮАР, Южный Судан, Новая Каледония",
         [names.country_of(x) for x in ("Ν. Ζηλανδία", "Ν. Αφρική", "Ν. Σουδάν", "Ν. Καληδονία")],
         ["NEW ZEALAND", "SOUTH AFRICA", "SOUTH SUDAN", "NEW CALEDONIA"])
проверка("«Β.» — «Βόρεια»: Северная Корея, Северная Ирландия, Северная Македония; «Α.» — «Ανατολικό»: Восточный Тимор",
         [names.country_of(x) for x in ("Β. Κορέα", "Β. Ιρλανδία", "Β. Μακεδονία", "Α. Τιμόρ")],
         ["NORTH KOREA", "NORTHERN IRELAND", "NORTH MACEDONIA", "TIMOR LESTE"])
проверка("Северная и Южная Корея по-гречески между собой не сходятся ни сокращённо, ни полностью",
         [names.similarity(a, b) < canon.SURE for a, b in (("Ν. Κορέα", "Β. Κορέα"), ("Β. Κορέα", "South Korea"),
                                                           ("Νότια Κορέα", "Βόρεια Κορέα"), ("Β. Κορέα", "Νότια Κορέα"))],
         [True] * 4)
проверка("«Β. Κορέα» сходится с North Korea, полное «Νότια Κορέα» — с сокращённым",
         (names.similarity("Β. Κορέα", "North Korea"), names.similarity("Β. Κορέα", "Korea DPR"),
          names.similarity("Ν. Κορέα", "Νότια Κορέα")), (100, 100, 100))
проверка("пол и возраст не теряются и стране не мешают; на витрину имя идёт по-английски",
         (names.country_of("Ν. Κορέα Γ"), names.category("Ν. Κορέα Γ"), names.country_of("Ν. Κορέα U20"),
          names.category("Ν. Κορέα U20"), names.suggest_canonical("Ν. Κορέα Γ"), names.suggest_canonical("Ν. Κορέα U20"),
          names.known_team("Ν. Κορέα")),
         ("SOUTH KOREA", "W", "SOUTH KOREA", "U20", "South Korea W", "South Korea U20", "SOUTH KOREA"))
проверка("имя заглавными буквами читается так же", names.country_of("Ν. ΚΟΡΕΑ"), "SOUTH KOREA")

print("Г4. Раскрытие не узнано — имя читается буквами, как раньше")
проверка("клуб «Ν. Ιωνία», школа эталона «Ν. Καρλάινα Α&Τ», «Ν. Μπριάνσκ»: не страны, чтение прежнее",
         [(names.country_of(x), names.readings(x)) for x in ("Ν. Ιωνία", "Ν. Καρλάινα Α&Τ", "Ν. Μπριάνσκ")],
         [("", ("N IONIA",)), ("", ("N KARLAINA A T", "N KARLAINA AT")), ("", ("N BRIANSK",))])
проверка("«Ν. Ιωνία» сходится с «Nea Ionia» и не сходится с чужой «Dafni Ionia»; «N. Carolina A&T» — со своей записью",
         (names.similarity("Ν. Ιωνία", "Nea Ionia"), names.similarity("Ν. Ιωνία", "Dafni Ionia") < canon.SURE,
          names.similarity("Ν. Καρλάινα Α&Τ Γ", "N. Carolina A&T W") >= canon.SURE), (100, True, True))
проверка("игрок с инициалом ПЕРЕД фамилией — не страна и читается как раньше",
         (names.country_of("Ν. Τζόκοβιτς"), names.readings("Ν. Τζόκοβιτς"), names.similarity("Ν. Τζόκοβιτς", "Djokovic N.")),
         ("", ("N TZOKOVITS",), names.similarity("Τζόκοβιτς Ν.", "Djokovic N.")))
проверка("две буквы подряд — аббревиатура клуба, не сторона света: «Α.Ε. Θράκης», «Α.Ο. Τυμπακίου», «Λ.Δ. Κονγκό»",
         [names._compass_spellings(x) for x in ("Α.Ε. Θράκης", "Α.Ο. Τυμπακίου", "Λ.Δ. Κονγκό", "Π.Α.Σ. Πύργος")], [()] * 4)
проверка("сокращение не в начале имени и латинская буква с точкой правило не трогает",
         [names._compass_spellings(x) for x in ("Ποσειδώνας Ν. Μηχανιώνας", "N. Korea", "N. Carolina A&T", "Н. Новгород")],
         [()] * 4)

print("Г2–Г3. Подтверждённое имя (словарь владельца) — тоже точное знание")
names.set_overrides({"Νέα Ιωνία": "Nea Ionia"})
try:
    проверка("подтверждена «Νέα Ιωνία» — «Ν. Ιωνία» читается ею и известна словарю",
             (names.readings("Ν. Ιωνία"), names.known_team("Ν. Ιωνία"), names.country_of("Ν. Ιωνία")),
             (("NEA IONIA",), "Nea Ionia", ""))
finally:
    names.set_overrides({})

print("Г5. Буква после фамилии — инициал человека (книги 141 и 146), правило его не трогает")
проверка("«Μεντβέντεφ Ν. (Κοσ)» сходится с «Ντανιίλ Μεντβέντεφ», «Σέλτον Μ.» — с «Μπεν Σέλτον»; чужой Медведев — нет",
         (names.similarity("Ντανιίλ Μεντβέντεφ", "Μεντβέντεφ Ν. (Κοσ)"), names.similarity("Μπεν Σέλτον", "Σέλτον Μ. (Ηπα)"),
          names.similarity("Αλεξάντερ Μεντβέντεφ", "Μεντβέντεφ Ν. (Κοσ)") < canon.SURE), (100, 100, True))

print(f"\nпроверок: {зелёных + красных}, зелёных: {зелёных}, красных: {красных}")
sys.exit(1 if красных else 0)
