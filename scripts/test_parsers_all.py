"""Книга 128 (15.11): тест для ВСЕХ разборщиков сайтов — и для тех, у кого
своего теста нет (опись 14.11: тестами не были упомянуты 65 модулей из 88).

Два слоя:
  Р1. Здесь, без страниц сайтов: каждый разборщик на пустой странице, на
      странице без расписания и на пустом служебном ответе отдаёт пустой
      список и не падает. Сайт лёг, отдал заглушку или пустой ответ — сбор
      из-за этого не должен ломаться.
  Р2. На настоящих страницах: `proverka.py --sravnit` (и проверка на GitHub
      на свежем сборе) разбирает сбор старым кодом и новым и сверяет счёт
      сырых строк по каждому сайту (`proverka.raw_losses`): сайт давал
      строки, а новым кодом дал вдвое меньше или ноль — выкладка красная.
      Страницы сайтов в репозитории при этом не хранятся.

Запуск: python scripts/test_parsers_all.py
"""
from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))
sys.stdout.reconfigure(encoding="utf-8")

from app import parsers  # noqa: E402
import proverka  # noqa: E402

зелёных = красных = 0


def проверка(имя: str, вышло, ждём=True) -> None:
    global зелёных, красных
    if вышло == ждём:
        зелёных += 1
        print(f"  ✔ {имя}")
    else:
        красных += 1
        print(f"  ✘ {имя}: вышло {вышло!r}, ждём {ждём!r}")


#: страницы без расписания: пустая, пустой HTML, заглушка, пустые служебные ответы
ПУСТЫЕ = {
    "пустая страница": "",
    "HTML без расписания": "<html><head><title>x</title></head><body><p>Нет данных</p></body></html>",
    "таблица без расписания": "<html><body><table><tr><td>x</td></tr></table></body></html>",
    "пустой служебный ответ": "{}",
    "служебный ответ с пустыми списками": '{"shows": [], "data": null, "items": [], "events": []}',
}


def вызвать(parse, text: str, domain: str):
    try:
        return parse(text, day=date(2026, 11, 15), tz="Europe/Kyiv", url=f"https://{domain}/x")
    except TypeError as e:
        if "unexpected keyword" not in str(e):
            raise
        return parse(text)                    # разбор без этих параметров


print("Р1. Каждый разборщик на странице без расписания отдаёт пустой список и не падает")
все = parsers.all_parsers()
модулей = {p.__module__ for p in все.values()}
проверка("разборщиков не меньше 85 модулей и 110 сайтов (никто не отвалился при загрузке)",
         (len(модулей) >= 85, len(все) >= 110), (True, True))
for имя, страница in ПУСТЫЕ.items():
    плохие = []
    for domain, parse in sorted(все.items()):
        try:
            got = вызвать(parse, страница, domain)
            if got != []:
                плохие.append(f"{domain}: отдал {type(got).__name__} длиной "
                              f"{len(got) if hasattr(got, '__len__') else '?'}")
        except Exception as e:                # noqa: BLE001
            плохие.append(f"{domain}: {type(e).__name__}: {str(e)[:60]}")
    проверка(f"{имя}: все {len(все)} разборов — пустой список", плохие, [])

print("Р2. Сторож разборщиков на сборе: счёт сырых строк по сайтам")
старый = {"разобрано": {"a.tv": 100, "b.tv": 40, "c.tv": 3, "d.tv": 60, "e.tv": 10}}
новый = {"разобрано": {"a.tv": 96, "b.tv": 0, "c.tv": 0, "d.tv": 29, "e.tv": 5, "f.tv": 7}}
потери = proverka.raw_losses(старый, новый)
проверка("ноль вместо строк и падение больше чем вдвое — потеря; малый сайт и малая просадка — нет",
         потери, ["разборщик b.tv: строк со страниц было 40, стало 0",
                  "разборщик d.tv: строк со страниц было 60, стало 29"])
проверка("ровно половина — ещё не потеря; новый сайт — не судим",
         any("e.tv" in x or "f.tv" in x for x in потери), False)
проверка("счёт не изменился — потерь нет", proverka.raw_losses(старый, старый), [])
проверка("в разборе нет счёта (старый файл) — без падения, потерь нет",
         proverka.raw_losses({}, {"разобрано": None}), [])

print(f"\nпроверок: {зелёных + красных}, зелёных: {зелёных}, красных: {красных}")
sys.exit(1 if красных else 0)
