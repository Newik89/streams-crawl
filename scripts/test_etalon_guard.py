# -*- coding: utf-8 -*-
r"""Сторож эталона и запись «сайт просел на дату» (книга 114, аудит 13.11.2026).

Правила — в шапке `app/etalon_guard.py`. Здесь на каждое — проверка:

Э1. ноль футбола в ближайшие дни — эталон пустой;
Э2. день стал меньше 60 % прошлого сбора той же даты — эталон урезан;
Э3. сегодняшний день по доле не судим;
Э4. без прошлого сбора работает только правило нуля;
С1–С4. просадка сайта на дату: только будущие дни обоих сборов, меньше
       половины, счёт «подряд» от числа до просадки.

В сеть не ходит:

    python scripts/test_etalon_guard.py
"""

from __future__ import annotations

import sys
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.stdout.reconfigure(encoding="utf-8")

from app import etalon_guard as g  # noqa: E402

passed, failed = 0, []


def check(name, cond, extra=""):
    global passed
    if cond:
        passed += 1
        print("  ✔", name)
    else:
        failed.append(name)
        print("  ✖", name, extra)


СЕГОДНЯ = date(2026, 11, 13)


def день(сдвиг: int) -> str:
    return (СЕГОДНЯ + timedelta(days=сдвиг)).isoformat()


def эталон(по_дням: dict) -> list:
    """{сдвиг дня: (футбол, баскетбол)} → записи эталона."""
    out = []
    for сдвиг, (ф, б) in по_дням.items():
        out += [{"start_kyiv": f"{день(сдвиг)}T18:00", "sport": "F"}] * ф
        out += [{"start_kyiv": f"{день(сдвиг)}T19:00", "sport": "B"}] * б
    return out


# живые числа сборов 13.11: сегодня, завтра … +6 дней
НОРМА = {0: (242, 155), 1: (1241, 463), 2: (949, 335), 3: (122, 71),
         4: (212, 180), 5: (206, 217), 6: (103, 204)}
ПРОШЛЫЙ = {0: (251, 200), 1: (1242, 464), 2: (950, 335), 3: (121, 71),
           4: (211, 180), 5: (203, 217), 6: (99, 204)}

print("Э. Эталон")
check("обычный сбор — норма",
      g.etalon_verdict(эталон(НОРМА), эталон(ПРОШЛЫЙ), СЕГОДНЯ) == [])
причины = g.etalon_verdict([], эталон(ПРОШЛЫЙ), СЕГОДНЯ)
check("Э1: пустой эталон — причина на каждый из шести ближайших дней",
      sum("нет ни одного футбольного" in r for r in причины) == 6, причины)
check("Э1: строка оценки начинается с ::error:: и называет эталон",
      g.etalon_error(причины).startswith("::error::эталон flashscore"))
check("норма — строка оценки пустая", g.etalon_error([]) == "")
без_дня = {**НОРМА, 2: (0, 0)}
причины = g.etalon_verdict(эталон(без_дня), эталон(ПРОШЛЫЙ), СЕГОДНЯ)
check("Э1: пропал один день целиком — назван этот день",
      any(день(2) in r and "нет ни одного футбольного" in r for r in причины),
      причины)
check("ноль футбола назван один раз, баскетбол — отдельно",
      sum(день(2) in r for r in причины) == 2, причины)
половина = {k: (ф // 2, б // 2) for k, (ф, б) in НОРМА.items()}
причины = g.etalon_verdict(эталон(половина), эталон(ПРОШЛЫЙ), СЕГОДНЯ)
check("Э2: эталон урезан вдвое — тревога по будущим дням",
      any(день(1) in r and "футбол: 620" in r for r in причины), причины)
check("Э3: сегодняшний день по доле не судим",
      not any(день(0) in r for r in причины), причины)
две_трети = {k: (ф * 2 // 3, б * 2 // 3) for k, (ф, б) in НОРМА.items()}
check("Э2: две трети от прошлого — ещё норма",
      g.etalon_verdict(эталон(две_трети), эталон(ПРОШЛЫЙ), СЕГОДНЯ) == [])
вечер = {**НОРМА, 0: (40, 10)}
check("Э3: к вечеру сегодняшних матчей мало — норма",
      g.etalon_verdict(эталон(вечер), эталон(ПРОШЛЫЙ), СЕГОДНЯ) == [])
мелочь_было = {**ПРОШЛЫЙ, 7: (3, 19)}
мелочь_стало = {**НОРМА, 7: (1, 5)}
check("Э2: день с малым числом матчей в прошлом сборе не судим",
      g.etalon_verdict(эталон(мелочь_стало), эталон(мелочь_было), СЕГОДНЯ) == [])
check("Э4: прошлого сбора нет, эталон полный — норма",
      g.etalon_verdict(эталон(НОРМА), [], СЕГОДНЯ) == [])
check("Э4: прошлого сбора нет, эталон пустой — тревога",
      len(g.etalon_verdict([], [], СЕГОДНЯ)) == 6)
теннис = эталон(НОРМА) + [{"start_kyiv": f"{день(1)}T10:00", "sport": "T"}] * 3
теннис_было = эталон(ПРОШЛЫЙ) + [{"start_kyiv": f"{день(1)}T10:00", "sport": "T"}] * 90
check("теннис не считаем: 90 → 3 матча — норма",
      g.etalon_verdict(теннис, теннис_было, СЕГОДНЯ) == [])

print("С. Сайт просел на дату (только запись)")


def игры(по_сайтам: dict) -> list:
    """{(сайт, сдвиг дня): число игр} → игры games.json."""
    out = []
    for (сайт, сдвиг), n in по_сайтам.items():
        for i in range(n):
            out.append({"start_kyiv": f"{день(сдвиг)}T{10 + i % 10}:00",
                        "entries": [{"source": сайт,
                                     "start_kyiv": f"{день(сдвиг)}T{10 + i % 10}:00"}]})
    return out


def прошлый(по_сайтам, окно=6, собрано=None, просадки=None):
    return {"games": игры(по_сайтам), "окно": окно,
            "собрано": собрано or f"{день(0)} 07:52", "просадки": просадки or []}


было = {("a.example", 0): 20, ("a.example", 1): 12, ("a.example", 2): 9,
        ("b.example", 1): 10, ("c.example", 1): 4, ("a.example", 5): 8}
стало = {("a.example", 0): 3, ("a.example", 1): 12, ("a.example", 2): 2,
         ("b.example", 1): 6, ("c.example", 1): 0}
п = g.site_drops(игры(стало), прошлый(было), СЕГОДНЯ, 6)
check("С3: просел один сайт на одну дату (9 → 2)",
      [(x["сайт"], x["дата"], x["было"], x["стало"]) for x in п]
      == [("a.example", день(2), 9, 2), ("a.example", день(5), 8, 0)], п)
check("С2: сегодняшний день не считаем (20 → 3 сегодня — не просадка)",
      not any(x["дата"] == день(0) for x in п))
check("С3: 10 → 6 — больше половины, не просадка",
      not any(x["сайт"] == "b.example" for x in п))
check("С3: у сайта было меньше 6 игр — не судим",
      not any(x["сайт"] == "c.example" for x in п))
п2 = g.site_drops(игры(стало), прошлый(было), СЕГОДНЯ, 2)
check("С2: новое окно 2 дня — дальние дни не сравниваем",
      not any(x["дата"] >= день(2) for x in п2), п2)
п3 = g.site_drops(игры(стало), прошлый(было, окно=2), СЕГОДНЯ, 6)
check("С2: прошлый сбор был на 2 дня — дальние дни не сравниваем",
      not any(x["дата"] >= день(2) for x in п3), п3)
check("первая просадка — «подряд» 1", all(x["подряд"] == 1 for x in п))
# следующий сбор: прошлый — уже просевший, запись о просадке едет в нём
п4 = g.site_drops(игры(стало), прошлый(стало, просадки=п), СЕГОДНЯ, 6)
check("С4: просадка держится второй сбор — «подряд» 2, «было» прежнее",
      [(x["дата"], x["было"], x["подряд"]) for x in п4
       if x["дата"] == день(2)] == [(день(2), 9, 2)], п4)
вернулось = {**стало, ("a.example", 2): 9}
п5 = g.site_drops(игры(вернулось), прошлый(стало, просадки=п), СЕГОДНЯ, 6)
check("С4: сайт вернул игры — просадка снята",
      not any(x["дата"] == день(2) for x in п5), п5)
check("прошлого сбора нет — просадок нет",
      g.site_drops(игры(стало), {}, СЕГОДНЯ, 6) == [])
два = [{"start_kyiv": f"{день(1)}T18:00", "entries": [
    {"source": "www.a.example", "start_kyiv": f"{день(1)}T18:00"},
    {"source": "a.example", "start_kyiv": f"{день(1)}T18:00"}]}]
check("С1: два канала одного сайта у одной игры — одна игра сайта",
      g.site_counts(два)[("a.example", день(1))] == 1)

print(f"\nпройдено: {passed}, провалено: {len(failed)}")
for name in failed:
    print("  ✖", name)
sys.exit(1 if failed else 0)
