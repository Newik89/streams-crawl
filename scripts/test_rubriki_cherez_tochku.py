def разбор(сайт: str, заголовок: str, когда: tuple, пара: str = " ", эфир: str = "Прямая трансляция"):
    p = Program(channel_raw="Канал", title=заголовок, start=datetime(*когда, tzinfo=KYIV),
                live_raw=эфир, match_raw=пара)
    return pipeline.classify(p, M, виды, reference=ЭТАЛОН, langs=site_lang.of(сайт)), p


